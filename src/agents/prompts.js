/** Инструкции проекта: LCC.md / CLAUDE.md / AGENTS.md в корне (как в Claude Code). */
export function loadProjectInstructions(cwd) {
  for (const name of ['LCC.md', 'CLAUDE.md', 'AGENTS.md']) {
    const f = path.join(cwd, name);
    try {
      const text = fs.readFileSync(f, 'utf8').trim();
      if (text) return { name, text: text.slice(0, 20000) };
    } catch { /* нет файла */ }
  }
  return null;
}

export function buildSystemPrompt(role, cwd) {
  const parts = [BASE_POLICY, ROLE[role], `# Среда\n${platformPromptBlock(cwd)}\nДата: ${new Date().toISOString().slice(0, 10)}`];
  const proj = loadProjectInstructions(cwd);
  if (proj) parts.push(`# Инструкции проекта (${proj.name})\n${proj.text}`);
  return parts.join('\n\n');
}

